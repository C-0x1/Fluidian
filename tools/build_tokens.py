#!/usr/bin/env python3
"""Regenerate the design-token stylesheets from the engine's colour model.

    python3 tools/build_tokens.py

Writes ``runtime/tokens.css`` (the default light and dark tokens) and
``runtime/themes.css`` (one scoped block per preset in ``fluidian.colors.THEMES``).
Edit the presets in ``engine/fluidian/colors.py``, then run this script.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "engine"))
from fluidian import colors as K  # noqa: E402


def main():
    default = K.THEMES[K.DEFAULT_THEME]
    with open(os.path.join(ROOT, "runtime", "tokens.css"), "w", encoding="utf-8") as fh:
        fh.write("/* Default design tokens. Generated by tools/build_tokens.py from the engine's colour model; edit the presets there. */\n")
        fh.write(K.theme_css(':root, [data-scheme="light"]', default))
        fh.write(K.theme_css('[data-scheme="dark"]', K.DEFAULT_DARK))
    with open(os.path.join(ROOT, "runtime", "themes.css"), "w", encoding="utf-8") as fh:
        fh.write("/* Theme presets. Generated by tools/build_tokens.py; apply one with the Theme component or data-fl-theme. */\n")
        for name, spec in K.THEMES.items():
            fh.write(K.theme_css('[data-fl-theme="%s"]' % name, spec))
    schemes = {name: ("dark" if spec.get("dark") else "light") for name, spec in K.THEMES.items()}
    with open(os.path.join(ROOT, "runtime", "themes.js"), "w", encoding="utf-8") as fh:
        fh.write("// Theme preset index. Generated by tools/build_tokens.py.\n")
        fh.write("export const THEMES = %s;\n" % json.dumps(schemes, indent=2))
        fh.write("export const THEME_LABELS = %s;\n" % json.dumps({n: s["label"] for n, s in K.THEMES.items()}, indent=2))
    print("wrote runtime/tokens.css, runtime/themes.css and runtime/themes.js (%d presets)" % len(K.THEMES))


if __name__ == "__main__":
    main()
