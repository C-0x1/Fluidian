def kind_of(cap):
    return "direct" if cap.direct else ("hybrid" if cap.facts else "model")


def gen_capabilities():
    caps = registry.load_all()
    with open(os.path.join(ROOT, "spec", "capabilities.json"), encoding="utf-8") as fh:
        families = json.load(fh)["categories"]
    cfg = Config()
    cfg.offline = True
    cfg.data_dir = os.path.join(ROOT, ".fluidian", "docs")
    kernel = Kernel(cfg)
    for scope in ("personalization", "microphone"):
        kernel.invoke("trust.consent", {"scope": scope, "grant": True}, sid="docs")
    written = []
    index = [HEADER, BRAND.format(up="../../"), "# Capability reference\n",
             "Fluidian %s ships **%d capabilities** in **%d families**. Each one is declared once in the engine and is available to every SDK, "
             "either attached to a component with `.ai(\"id\")` or called from a handler with `ctx.ai(\"id\", input)`.\n" % (__version__, len(caps), len(families)),
             "| Kind | Count | Meaning |\n| --- | --- | --- |",
             "| model | %d | Answered by the model through strict Structured Outputs; a Reflex implementation answers offline. |" % sum(1 for c in caps.values() if kind_of(c) == "model"),
             "| hybrid | %d | The engine computes the facts deterministically; the model only writes the narrative around them. |" % sum(1 for c in caps.values() if kind_of(c) == "hybrid"),
             "| direct | %d | Computed entirely by the engine. No model call, no tokens, identical online and offline. |\n" % sum(1 for c in caps.values() if kind_of(c) == "direct"),
             "## Surfaces\n\nThe surface is how a result reaches the screen when the capability is attached to a component.\n",
             "| Surface | Behaviour |\n| --- | --- |\n" + "\n".join("| `%s` | %s |" % kv for kv in registry.PRESENTERS.items()) + "\n", "## Families\n"]
    for family in families:
        members = [c for c in caps.values() if c.id.split(".")[0] == family["id"]]
        index.append("### [%s](capabilities/%s.md)\n\n%s\n" % (family["title"], family["id"], family["blurb"]))
        index.append("| Capability | Title | Kind | Surface | What it does |\n| --- | --- | --- | --- | --- |")
        for cap in members:
            index.append("| [`%s`](capabilities/%s.md#%s) | %s | %s | `%s` | %s |" % (
                cap.id, family["id"], anchor("`%s` — %s" % (cap.id, cap.title)), cap.title, kind_of(cap), cap.present, cap.summary))
        index.append("")
        page = [HEADER, BRAND.format(up="../../../"), "# %s\n" % family["title"], "%s\n" % family["blurb"],
                "%d capabilities. [Back to the index](../capabilities.md)\n" % len(members),
                "\n".join("- [`%s`](#%s) — %s" % (c.id, anchor("`%s` — %s" % (c.id, c.title)), c.title) for c in members) + "\n"]
        for cap in members:
            page.append("---\n")
            page.append(capability_section(cap, kernel, kind_of(cap)))
        written.append(write("docs/reference/capabilities/%s.md" % family["id"], "\n".join(page)))
    written.append(write("docs/reference/capabilities.md", "\n".join(index)))
    return written


