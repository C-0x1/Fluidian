def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = text.rstrip() + "\n"
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old != text:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    return rel


def type_name(spec):
    """Human-readable name for a schema-notation fragment."""
    if isinstance(spec, tuple):
        return type_name(spec[0])
    if isinstance(spec, list):
        return "list of %s" % type_name(spec[0]) if spec else "list"
    if isinstance(spec, dict):
        return "object {%s}" % ", ".join(k.rstrip("?") for k in spec)
    text = str(spec)
    optional = text.endswith("?")
    text = text.rstrip("?")
    names = {"str": "string", "num": "number", "int": "integer", "bool": "boolean", "json": "JSON value", "node": "scene node", "any": "any"}
    out = "one of `%s`" % "`, `".join(text[5:].split("|")) if text.startswith("enum:") else names.get(text, text)
    return out + (" or null" if optional else "")


def describe(spec):
    return spec[1] if isinstance(spec, tuple) and len(spec) > 1 else ""


def fields_table(shape, required_column):
    if not isinstance(shape, dict) or not shape:
        return "_No fields._\n"
    notes = any(describe(spec) for spec in shape.values())
    lines = ["| Field | Type |%s%s" % (" Required |" if required_column else "", " Notes |" if notes else ""),
             "| --- | --- |%s%s" % (" --- |" if required_column else "", " --- |" if notes else "")]
    for key, spec in shape.items():
        need = (" %s |" % ("no" if key.endswith("?") else "yes")) if required_column else ""
        lines.append("| `%s` | %s |%s%s" % (key.rstrip("?"), type_name(spec), need, (" %s |" % describe(spec)) if notes else ""))
    return "\n".join(lines) + "\n"


def shorten(value, depth=0):
    """Trim example output so it stays readable in documentation."""
    if isinstance(value, dict):
        if depth >= 4:
            return {"…": "%d keys" % len(value)}
        return {k: ("…" if k in VOLATILE else shorten(v, depth + 1)) for k, v in value.items()}
    if isinstance(value, list):
        head = [shorten(v, depth + 1) for v in value[:3]]
        return head + (["… %d more" % (len(value) - 3)] if len(value) > 3 else [])
    if isinstance(value, str) and len(value) > 140:
        return value[:137] + "…"
    return value


def python_literal(value):
    return json.dumps(value, ensure_ascii=False).replace(": true", ": True").replace(": false", ": False").replace(": null", ": None")


def host_for(cap):
    bind = (cap.binds or ["Text"])[0]
    spec = next((c for c in C.COMPONENTS if c["type"] == bind), None)
    if not spec:
        return 'ui.text("…")'
    args = ", ".join(json.dumps(a) for a in (spec["example"].get("args") or []))
    return "ui.%s(%s)" % (spec["fn"], args)


def capability_section(cap, kernel, kind):
    out = ["### `%s` — %s\n" % (cap.id, cap.title), "%s\n" % cap.summary, "**Why it exists.** %s\n" % cap.why]
    facts = [("Kind", {"model": "model, with an offline Reflex implementation", "hybrid": "hybrid: the engine computes the facts, the model writes the narrative",
                       "direct": "direct: computed by the engine, no model call"}[kind]),
             ("Model tier", "—" if kind == "direct" else cap.tier), ("Surface", "`%s` — %s" % (cap.present, registry.PRESENTERS[cap.present])),
             ("Binds to", ", ".join("`%s`" % b for b in cap.binds) or "any component, or call it from code"),
             ("Consent", "`%s`" % cap.consent if cap.consent else "none"), ("Reads the scene", "yes" if cap.uses_scene else "no"),
             ("Uses registered actions", "yes" if cap.uses_actions else "no")]
    out.append("| | |\n| --- | --- |\n" + "\n".join("| %s | %s |" % row for row in facts) + "\n")
    out.append("**Input**\n\n" + fields_table(cap.inp, True))
    out.append("**Output**\n\n" + fields_table(cap.out, False))
    usage = []
    if cap.present not in ("service", "observe", "command", "chat"):
        usage.append("# attach it to a component\n%s.ai(\"%s\")" % (host_for(cap), cap.id))
    usage.append("# or call it from a handler\nresult = ctx.ai(\"%s\", %s)" % (cap.id, python_literal(shorten(cap.example))))
    out.append("**Use it**\n\n```python\n%s\n```\n" % "\n\n".join(usage))
    result = kernel.invoke(cap.id, cap.example, sid="docs", now=NOW, actions=registry_actions())
    if result.get("ok"):
        out.append("**Example result** (offline Reflex engine, from the input above)\n\n```json\n%s\n```\n" % json.dumps(shorten(result["data"]), indent=2, ensure_ascii=False))
    return "\n".join(out)


