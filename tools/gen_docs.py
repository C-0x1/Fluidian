def anchor(heading):
    """GitHub's heading-to-anchor rule: lowercase, drop punctuation, spaces to hyphens."""
    keep = "".join(ch for ch in heading.lower() if ch.isalnum() or ch in " -_")
    return keep.replace(" ", "-")


def gen_components():
    titles = COMPONENT_FAMILIES
    out = [HEADER, BRAND.format(up="../../"), "# Component reference\n",
           "%d components in %d groups. Every component accepts `.id()`, `.on(event, action)`, `.ai(capability)` and arbitrary props through `.prop(key, value)`. "
           "Factory names follow each language's conventions (`ui.text_area` in Python, `ui.textArea` in JavaScript, `UI.TextArea` in C#).\n" % (len(C.COMPONENTS), len(titles))]
    for group, title in titles.items():
        members = [c for c in C.COMPONENTS if c["category"] == group]
        out.append("## %s\n\n%s\n" % (title, " · ".join("[%s](#%s)" % (c["type"], c["type"].lower()) for c in members)))
        for spec in members:
            args = ", ".join(json.dumps(a) for a in (spec["example"].get("args") or []))
            chain = "".join(".prop(%s, %s)" % (json.dumps(k), python_literal(shorten(v))) for k, v in list((spec["example"].get("props") or {}).items())[:3])
            child = ("%sui.text(\"…\")" % (", " if args else "")) if spec["container"] else ""
            out.append("### %s\n\n%s%s\n" % (spec["type"], spec["summary"], " Container." if spec["container"] else ""))
            out.append("```python\nui.%s(%s%s)%s\n```\n" % (spec["fn"], args, child, chain))
            rows = ["| Prop | Type | Default | Description |", "| --- | --- | --- | --- |"]
            for name, meta in spec["props"].items():
                rows.append("| `%s`%s | %s | %s | %s |" % (name, " (argument)" if meta["arg"] else "", type_name(meta["kind"]),
                                                          "—" if meta["default"] is None else "`%s`" % json.dumps(meta["default"]), meta["doc"]))
            out.append("\n".join(rows) + "\n")
            if spec["events"]:
                out.append("Events: %s\n" % ", ".join("`%s`" % e for e in spec["events"]))
    return [write("docs/reference/components.md", "\n".join(out))]


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return fh.read().rstrip()


def run_block(lang, info):
    lines = []
    if info.get("build"):
        lines.append(info["build"])
    prefix = "cd %s && ../../fluidian run -- " % info["cwd"] if info.get("cwd") else "./fluidian run -- "
    lines.append(prefix + info["run"])
    return "```bash\n%s\n```" % "\n".join(lines)


