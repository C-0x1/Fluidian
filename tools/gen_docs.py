def fill(text, marker, body):
    """Replace the block between ``<!-- marker:start -->`` and ``<!-- marker:end -->``."""
    start, end = "<!-- %s:start -->" % marker, "<!-- %s:end -->" % marker
    if start not in text or end not in text:
        return text
    head, rest = text.split(start, 1)
    return head + start + "\n" + body.rstrip() + "\n" + end + rest.split(end, 1)[1]


