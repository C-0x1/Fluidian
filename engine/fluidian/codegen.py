def layout(lang: str, source: str, sdk_root: str) -> Dict[str, Any]:
    """Project files and commands for an application source in ``lang``.

    ``source`` is written the way a published package would be imported; the
    returned files import the SDK from ``sdk_root`` instead, so the project
    runs from a checkout without installing anything. Returns
    ``{"files": {path: text}, "build": [[argv], ...], "run": [argv], "main": path}``.
    """
    import json as _json
    import os as _os
    sdk = _os.path.join(sdk_root, lang)
    files: Dict[str, str] = {}
    build: List[List[str]] = []
    if lang == "python":
        files["app.py"], run = source, ["python3", "app.py"]
    elif lang == "javascript":
        files["app.js"], run = source.replace('require("fluidian")', "require(%s)" % _json.dumps(sdk)), ["node", "app.js"]
    elif lang == "typescript":
        files["app.ts"] = source.replace('from "fluidian"', "from %s" % _json.dumps(_os.path.join(sdk, "dist", "index")))
        files["tsconfig.json"] = _json.dumps({"compilerOptions": {"target": "ES2019", "module": "commonjs", "strict": True, "outDir": "dist", "skipLibCheck": True, "types": []},
                                              "files": ["app.ts"]}, indent=2) + "\n"
        build, run = [["tsc", "-p", sdk], ["tsc", "-p", "."]], ["node", _os.path.join("dist", "app.js")]
    elif lang == "go":
        files["main.go"] = source
        files["go.mod"] = "module app\n\ngo 1.18\n\nrequire github.com/fluidian/fluidian/sdks/go v1.2.0\n\nreplace github.com/fluidian/fluidian/sdks/go => %s\n" % sdk
        run = ["go", "run", "."]
    elif lang == "rust":
        files[_os.path.join("src", "main.rs")] = source
        files["Cargo.toml"] = '[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\nfluidian = { path = %s }\n' % _json.dumps(sdk)
        build, run = [["cargo", "build", "--quiet"]], ["cargo", "run", "--quiet"]
    elif lang == "java":
        files["Main.java"] = source
        build = [["javac", "-encoding", "UTF-8", "-nowarn", "-d", "out", "-sourcepath", _os.path.join(sdk, "src", "main", "java"), "Main.java"]]
        run = ["java", "-Dfile.encoding=UTF-8", "-cp", "out", "Main"]
    elif lang == "kotlin":
        files["app.kt"] = source
        build = [["kotlinc", _os.path.join(sdk, "src", "main", "kotlin"), "app.kt", "-include-runtime", "-nowarn", "-d", "app.jar"]]
        run = ["java", "-Dfile.encoding=UTF-8", "-cp", "app.jar", "AppKt"]
    elif lang == "csharp":
        files["Program.cs"] = source
        files["App.csproj"] = _CSPROJ % _os.path.join(sdk, "Fluidian", "Fluidian.csproj")
        files["NuGet.config"] = '<?xml version="1.0" encoding="utf-8"?>\n<configuration>\n  <packageSources>\n    <clear />\n  </packageSources>\n</configuration>\n'
        build = [["dotnet", "build", "-c", "Release", "-o", "out", "--nologo", "-v", "q", "-p:UseAppHost=false"]]
        run = ["dotnet", _os.path.join("out", "App.dll")]
    elif lang == "cpp":
        files["app.cpp"] = source
        build, run = [["g++", "-std=c++17", "-O1", "-I" + _os.path.join(sdk, "include"), "app.cpp", "-o", "app"]], ["./app"]
    elif lang == "ruby":
        files["app.rb"], run = source, ["ruby", "-I" + _os.path.join(sdk, "lib"), "app.rb"]
    elif lang == "php":
        files["app.php"] = source.replace("require __DIR__ . '/vendor/autoload.php';", "require %s;" % _json.dumps(_os.path.join(sdk, "src", "Fluidian.php")))
        run = ["php", "app.php"]
    elif lang == "dart":
        files["app.dart"] = source.replace("import 'package:fluidian/fluidian.dart';", "import %s;" % _json.dumps(_os.path.join(sdk, "lib", "fluidian.dart")))
        run = ["dart", "run", "app.dart"]
    elif lang == "elixir":
        head = "".join("Code.require_file(%s)\n" % _json.dumps(_os.path.join(sdk, "lib", p)) for p in ("fluidian.ex", _os.path.join("fluidian", "ui.ex")))
        files["app.exs"], run = head + "\n" + source, ["elixir", "app.exs"]
    elif lang == "lua":
        files["app.lua"] = "package.path = %s .. package.path\n" % _json.dumps(_os.path.join(sdk, "?.lua") + ";") + source
        run = ["lua5.4", "app.lua"]
    else:
        raise KeyError(lang)
    main = next(iter(files))  # every branch above adds the application source first
    return {"files": files, "build": build, "run": run, "main": main}


MANIFEST = "fluidian.project.json"


def write_project(lang: str, directory: str, source: str, sdk_root: str, extra: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Write ``source`` as a runnable project and record how to build and run it in ``fluidian.project.json``."""
    import json as _json
    import os as _os
    project = layout(lang, source, sdk_root)
    manifest = dict({"language": lang, "main": project["main"], "build": project["build"], "run": project["run"]}, **(extra or {}))
    project["files"][MANIFEST] = _json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    for rel, text in project["files"].items():
        path = _os.path.join(directory, rel)
        _os.makedirs(_os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    return {"files": sorted(project["files"]), "build": project["build"], "run": project["run"], "main": project["main"]}


def scaffold(lang: str, directory: str, title: str, scene: Dict[str, Any], sdk_root: str) -> Dict[str, Any]:
    """Write a starter project that runs as it is against the SDKs in ``sdk_root``.

    Returns ``{"files": [...], "build": [[argv], ...], "run": [argv]}``; ``run`` is what goes after ``fluidian run --``.
    """
    return write_project(lang, directory, emit_app(scene, lang, title), sdk_root, {"name": title})
