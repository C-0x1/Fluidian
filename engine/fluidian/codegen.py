def emit_app(scene: Dict[str, Any], lang: str, title: str = "My app") -> str:
    """A complete application: imports, view, a handler per bound action, run."""
    e = EMITTERS[lang]
    actions: List[str] = []
    for node, _, _ in C.walk(scene):
        for binding in (node.get("on") or {}).values():
            name = binding if isinstance(binding, str) else binding.get("action")
            if name and name not in actions:
                actions.append(name)
    handlers = "".join(_HANDLER[lang].format(a=e.s(a), f=re.sub(r"\W+", "_", a), m=e.s("%s received" % a.replace("_", " ").capitalize()))
                       for a in actions)
    return _APP[lang].format(title=e.s(title), scene=e.node(scene, _PAD[lang]), handlers=handlers)


