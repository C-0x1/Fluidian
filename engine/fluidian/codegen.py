def _factory(lang: str, spec: Dict[str, Any]) -> str:
    renamed = [a["name"] for a in spec["args"] if a["name"] in _RESERVED.get(lang, ())]
    if renamed:
        safe = dict(spec, args=[dict(a, name=a["name"] + "_") if a["name"] in renamed else a for a in spec["args"]])
        text = _factory_raw(lang, safe)
        for name in renamed:
            text = text.replace('"%s_"' % name, '"%s"' % name).replace("'%s_'" % name, "'%s'" % name)
        return text
    return _factory_raw(lang, spec)


def _factory_raw(lang: str, spec: Dict[str, Any]) -> str:
    e = EMITTERS[lang]
    fn, typ, doc = e.fn(spec["fn"]), spec["type"], spec["summary"]
    args = [(a["name"], a["kind"]) for a in spec["args"]]
    names = [n for n, _ in args]
    box = spec["container"]
    T = _TYPES.get(lang, {})
    if lang == "python":
        sig = ", ".join(["%s%s" % (n, ": str" if k == "str" else ": float") for n, k in args] + (["*children: Node"] if box else []))
        body = "Node(%r)" % typ + "".join('.prop("%s", %s)' % (n, n) for n in names) + (".add(*children)" if box else "")
        return 'def %s(%s) -> Node:\n    """%s"""\n    return %s\n' % (fn, sig, doc, body.replace("'", '"'))
    if lang in ("javascript", "typescript"):
        ts = lang == "typescript"
        sig = ", ".join(["%s%s" % (n, (": " + T[k]) if ts else "") for n, k in args] + (["...children" + (": Node[]" if ts else "")] if box else []))
        body = 'new Node("%s")' % typ + "".join('.prop("%s", %s)' % (n, n) for n in names) + (".add(...children)" if box else "")
        return "  /** %s */\n  %s(%s)%s {\n    return %s;\n  },\n" % (doc, fn, sig, ": Node" if ts else "", body)
    if lang == "go":
        sig = ", ".join(["%s %s" % (n, T[k]) for n, k in args] + (["children ...*Node"] if box else []))
        body = 'NewNode("%s")' % typ + "".join('.Prop("%s", %s)' % (n, n) for n in names) + (".Add(children...)" if box else "")
        return "// %s %s\nfunc %s(%s) *Node {\n\treturn %s\n}\n" % (fn, doc[0].lower() + doc[1:], fn, sig, body)
    if lang == "rust":
        sig = ", ".join(["%s: %s" % (n, T[k]) for n, k in args] + (["children: Vec<Node>"] if box else []))
        body = 'Node::new("%s")' % typ + "".join('.prop("%s", %s)' % (n, n if k == "str" else "Into::<f64>::into(%s)" % n) for n, k in args) + (".add(children)" if box else "")
        return "/// %s\npub fn %s(%s) -> Node {\n    %s\n}\n" % (doc, fn, sig, body)
    if lang in ("java", "kotlin", "csharp", "dart"):
        N = {"java": "prop", "kotlin": "prop", "csharp": "Prop", "dart": "prop"}[lang]
        A = {"java": "add", "kotlin": "add", "csharp": "Add", "dart": "addAll"}[lang]
        if lang == "kotlin":
            sig = ", ".join(["%s: %s" % (n, T[k]) for n, k in args] + (["vararg children: Node"] if box else []))
            body = 'Node("%s")' % typ + "".join('.prop("%s", %s)' % (n, n) for n in names) + (".add(*children)" if box else "")
            return "    /** %s */\n    @JvmStatic fun %s(%s): Node = %s\n" % (doc, fn, sig, body)
        vararg = {"java": "Node... children", "csharp": "params Node[] children", "dart": "[List<Node> children = const []]"}[lang]
        sig = ", ".join(["%s %s" % (T[k], n) for n, k in args] + ([vararg] if box else []))
        new = "new Node" if lang in ("java", "csharp") else "Node"
        body = '%s("%s")' % (new, typ) + "".join('.%s("%s", %s)' % (N, n, n) for n in names) + (".%s(children)" % A if box else "")
        if lang == "dart":
            return "  /// %s\n  static Node %s(%s) => %s;\n" % (doc, fn, sig, body)
        if lang == "java":
            return "    /** %s */\n    public static Node %s(%s) {\n        return %s;\n    }\n" % (doc, fn, sig, body)
        return "    /// <summary>%s</summary>\n    public static Node %s(%s) => %s;\n" % (doc.replace("&", "and").replace("<", "(").replace(">", ")"), fn, sig, body)
    if lang == "cpp":
        sig = ", ".join(["%s %s" % (T[k], n) for n, k in args] + (["std::initializer_list<Node> children = {}"] if box else []))
        body = 'Node("%s")' % typ + "".join('.prop("%s", %s)' % (n, n) for n in names) + (".add(children)" if box else "")
        return "/// %s\ninline Node %s(%s) { return %s; }\n" % (doc, fn, sig, body)
    if lang == "ruby":
        sig = ", ".join(names + (["*children"] if box else []))
        body = 'Node.new("%s")' % typ + "".join('.prop("%s", %s)' % (n, n) for n in names) + (".add(*children)" if box else "")
        return "    # %s\n    def self.%s(%s)\n      %s\n    end\n" % (doc, fn, sig, body)
    if lang == "php":
        sig = ", ".join(["%s $%s" % ("string" if k == "str" else "int|float", n) for n, k in args] + (["Node ...$children"] if box else []))
        body = "(new Node('%s'))" % typ + "".join("->prop('%s', $%s)" % (n, n) for n in names) + ("->add(...$children)" if box else "")
        return "    /** %s */\n    public static function %s(%s): Node\n    {\n        return %s;\n    }\n" % (doc, fn, sig, body)
    if lang == "elixir":
        sig = ", ".join(names + (["children \\\\ []"] if box else []))
        body = 'Node.new("%s")' % typ + "".join(' |> Node.prop("%s", %s)' % (n, n) for n in names) + (" |> Node.add(children)" if box else "")
        return '  @doc "%s"\n  def %s(%s), do: %s\n' % (doc.replace('"', "'"), fn, sig, body)
    if lang == "lua":
        sig = ", ".join(names + (["..."] if box else []))
        body = 'Node.new("%s")' % typ + "".join(':prop("%s", %s)' % (n, n) for n in names) + (":add(...)" if box else "")
        return "--- %s\nfunction ui.%s(%s)\n  return %s\nend\n" % (doc, fn, sig, body)
    raise KeyError(lang)


