def conformance_scene() -> Dict[str, Any]:
    """One instance of every component, built from the registry examples."""
    kids = []
    for spec in C.COMPONENTS:
        ex = spec["example"]
        props = dict(ex.get("props") or {})
        for a, v in zip(spec["args"], ex.get("args") or []):
            props[a["name"]] = v
        node: Dict[str, Any] = {"type": spec["type"], "props": props}
        if spec["container"]:
            node["children"] = [{"type": "Text", "props": {"content": "Inside %s" % spec["type"]}}]
        kids.append(node)
    kids[2]["id"] = "sample-stack"
    kids.append({"type": "Button", "id": "extras", "props": {"label": "Bindings", "kbd": None, "disabled": False, "size": "lg"},
                 "on": {"click": {"action": "go", "payload": {"route": "/details", "n": 3, "ratio": 0.5, "tags": ["a", "b"], "nested": {"ok": True, "none": None}}}},
                 "ai": [{"capability": "content.microcopy", "options": {}}, {"capability": "input.ghost", "options": {"context": "demo $HOME #{x} \"q\" \\ end"}}]})
    return {"type": "Stack", "id": "all-components", "props": {"gap": "lg"}, "children": kids}


