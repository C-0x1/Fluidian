def camel(snake: str) -> str:
    head, *rest = snake.split("_")
    return head + "".join(p.capitalize() for p in rest)


def pascal(snake: str) -> str:
    return "".join(p.capitalize() for p in snake.split("_"))


def _esc(text: str, ctrl: Callable[[int], str], dollar: bool = False, interp: str = "") -> str:
    out = []
    for i, ch in enumerate(text):
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7f:
            out.append(ctrl(code))
        elif ch == "$" and dollar:
            out.append("\\$")
        elif ch == "#" and interp and text[i + 1:i + 2] in interp:
            out.append("\\#")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


_U4 = lambda c: "\\u%04x" % c  # noqa: E731
_UB = lambda c: "\\u{%x}" % c  # noqa: E731


class Lang:
    """Syntax description of one target language."""
    name = ""
    case = "snake"            # factory naming
    ns = "ui."                # prefix before a factory name
    list_children = False     # children passed as one list argument instead of varargs
    methods = {"prop": "prop", "id": "id", "on": "on", "ai": "ai"}
    with_suffix = False       # on/ai variants taking an extra argument use a *With / *_with name
    null, true, false = "null", "true", "false"
    step = "  "               # indentation unit for nested children

    def s(self, text: str) -> str:
        return _esc(text, _U4)

    def fn(self, snake: str) -> str:
        return {"snake": snake, "camel": camel(snake), "pascal": pascal(snake)}[self.case]

    def num(self, v: Any) -> str:
        return repr(v) if isinstance(v, float) else str(v)

    def arr(self, parts: List[str]) -> str:
        return "[" + ", ".join(parts) + "]"

    def obj(self, pairs: List[tuple]) -> str:
        return "{" + ", ".join("%s: %s" % (self.s(k), v) for k, v in pairs) + "}"

    def lit(self, v: Any) -> str:
        if v is None:
            return self.null
        if isinstance(v, bool):
            return self.true if v else self.false
        if isinstance(v, (int, float)):
            return self.num(v)
        if isinstance(v, str):
            return self.s(v)
        if isinstance(v, (list, tuple)):
            return self.arr([self.lit(x) for x in v])
        if isinstance(v, dict):
            return self.obj([(str(k), self.lit(x)) for k, x in v.items()])
        return self.s(str(v))

    def children(self, parts: List[str], pad: str) -> str:
        inner = (",\n" + pad + self.step).join(parts)
        return "\n%s%s%s\n%s" % (pad, self.step, inner, pad) if parts else ""

    def wrap_list(self, body: str) -> str:
        return "[" + body + "]"

    def chain(self, expr: str, method: str, args: List[str]) -> str:
        return "%s.%s(%s)" % (expr, method, ", ".join(args))

    def call(self, fn_name: str, args: List[str]) -> str:
        return "%s%s(%s)" % (self.ns, fn_name, ", ".join(args))

    # --- scene emission ----------------------------------------------------
    def node(self, node: Dict[str, Any], pad: str = "") -> str:
        spec = C.SPEC[node["type"]]
        props = dict(node.get("props") or {})
        args = []
        for a in spec["args"]:
            v = props.pop(a["name"], None)
            args.append(self.lit(v if v is not None else ("" if a["kind"] == "str" else 0)))
        kids = [self.node(c, pad + self.step) for c in node.get("children") or []]
        name = self.fn(spec["fn"])
        if spec["container"] and self.list_children:
            expr = self.call(name, args + [self.wrap_list(self.children(kids, pad))])
        elif spec["container"] and kids:
            expr = "%s%s(%s%s)" % (self.ns, name, (", ".join(args) + ",") if args else "", self.children(kids, pad))
        else:
            expr = self.call(name, args)
        m = self.methods
        for key, value in props.items():
            expr = self.chain(expr, m["prop"], [self.s(key), self.lit(value)])
        if node.get("id") and not C.is_auto_id(node.get("id")):
            expr = self.chain(expr, m["id"], [self.s(node["id"])])
        for event, binding in (node.get("on") or {}).items():
            binding = {"action": binding} if isinstance(binding, str) else binding
            if "payload" in binding:
                expr = self.chain(expr, m["on"] + self._with(), [self.s(event), self.s(binding["action"]), self.lit(binding["payload"])])
            else:
                expr = self.chain(expr, m["on"], [self.s(event), self.s(binding["action"])])
        for binding in node.get("ai") or []:
            binding = {"capability": binding} if isinstance(binding, str) else binding
            if binding.get("options"):
                expr = self.chain(expr, m["ai"] + self._with(), [self.s(binding["capability"]), self.lit(binding["options"])])
            else:
                expr = self.chain(expr, m["ai"], [self.s(binding["capability"])])
        return expr

    def _with(self) -> str:
        return "" if not self.with_suffix else ("With" if self.case == "pascal" else "_with")


